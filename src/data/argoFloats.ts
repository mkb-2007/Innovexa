import type { ArgoFloat, DepthMeasurement } from "@/types/globe";

export function generateDepthProfile(
  surfaceTemp: number,
  surfaceSalinity: number,
  maxDepth: number = 2000
): DepthMeasurement[] {
  const depths =
    maxDepth === 6000
      ? [0, 50, 100, 200, 500, 1000, 2000, 3000, 4000, 5000, 6000]
      : [0, 50, 100, 200, 500, 1000, 1500, 2000];

  return depths.map((d) => {
    // Thermocline model: sharp drop in upper 500m, flattening out at depth
    const tempDrop = Math.min(
      surfaceTemp - 1.5,
      (surfaceTemp - 2.2) * (1 - Math.exp(-d / 280))
    );
    const temp = Math.max(0.8, Number((surfaceTemp - tempDrop).toFixed(2)));

    // Halocline model: salinity variations
    const sal = Number(
      (
        surfaceSalinity +
        (d < 300 ? 0.3 * Math.sin(d / 80) : -0.15 * Math.exp(-d / 1000))
      ).toFixed(2)
    );
    const oxy = Number(
      (210 - (d < 400 ? 120 * (d / 400) : 60 * Math.exp(-d / 1500))).toFixed(1)
    );

    return {
      depth: d,
      temperature: temp,
      salinity: sal,
      oxygen: oxy,
      pressure: Number((d * 1.01).toFixed(1)),
    };
  });
}

